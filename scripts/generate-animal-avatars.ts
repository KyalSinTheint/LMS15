/**
 * Generates src/lib/animalAvatarIcons.ts: the animal artwork used for default
 * profile pictures, extracted from Microsoft Fluent Emoji (flat style, MIT
 * license) so the app bundles only these few icons.
 *
 *   npx tsx scripts/generate-animal-avatars.ts
 */
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const icons = require('@iconify-json/fluent-emoji-flat/icons.json') as {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
};

// Head-style animals that read well in a round frame (no pig: avoids offending
// colleagues for religious reasons).
const ANIMALS = [
  'cat-face', 'dog-face', 'fox', 'panda', 'koala', 'bear', 'polar-bear', 'lion', 'tiger-face', 'frog',
  'hamster', 'rabbit-face', 'monkey-face', 'mouse-face', 'wolf', 'raccoon', 'cow-face', 'unicorn', 'owl',
  'penguin', 'baby-chick',
];

const out: Record<string, string> = {};
for (const name of ANIMALS) {
  const icon = icons.icons[name];
  if (!icon) throw new Error(`Icon not found: ${name}`);
  if ((icon.width ?? icons.width ?? 32) !== 32 || (icon.height ?? icons.height ?? 32) !== 32) {
    throw new Error(`Unexpected icon size for ${name}`);
  }
  out[name] = icon.body;
}

const file = `/* eslint-disable */
// GENERATED by scripts/generate-animal-avatars.ts. Do not edit by hand.
// Artwork: Microsoft Fluent Emoji (flat), MIT License, Copyright (c) Microsoft Corporation.
// https://github.com/microsoft/fluentui-emoji
// Each value is the inner SVG of a 32x32 icon.

export const ANIMAL_AVATAR_ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;

const target = path.resolve('src/lib/animalAvatarIcons.ts');
fs.writeFileSync(target, file);
console.log(`Wrote ${target} (${ANIMALS.length} animals, ${(file.length / 1024).toFixed(1)} KB)`);
