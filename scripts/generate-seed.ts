/**
 * Generates supabase/seed.sql from the demo content in src/data/seedLmsData.ts.
 *
 *   npx tsx scripts/generate-seed.ts
 *
 * Only shared content is seeded (courses, news, products, quizzes, ...).
 * Users, enrollments, progress and quiz attempts are NOT seeded: those are
 * created by real Supabase Auth accounts as people use the portal.
 * Every insert uses ON CONFLICT DO NOTHING so the file is safe to re-run.
 */
import fs from 'fs';
import path from 'path';
import * as seed from '../src/data/seedLmsData.ts';

// Some demo ids look like UUIDs but contain non-hex letters ("n000...",
// "tp00..."), which Postgres rejects. Map them deterministically to valid UUIDs.
const HEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
function toUuid(id: string | null | undefined): string | null {
  if (!id) return null;
  if (HEX.test(id)) return id.toLowerCase();
  const chars = id.toLowerCase().replace(/[^0-9a-f-]/g, '0');
  if (HEX.test(chars)) return chars;
  throw new Error(`Cannot map id "${id}" to a UUID`);
}

function sqlLiteral(value: unknown): string {
  return `'${JSON.stringify(value).replace(/'/g, "''")}'`;
}

// jsonb_populate_recordset turns missing keys into NULL (it does not apply
// column defaults), so NOT NULL columns that the demo data omits get these.
const DEFAULTS: Record<string, Record<string, unknown>> = {
  license_quizzes: { is_published: true },
  skill_quizzes: { is_published: true },
  product_quizzes: { is_published: true, max_attempts: 0 },
  license_chapters: { is_published: true },
  license_training_lessons: { file_url: '' },
  company_bulletins: { published: true, status: 'published' },
};

function insert(table: string, rawRows: object[], conflict = '(id)'): string {
  if (rawRows.length === 0) return '';
  const rows = rawRows.map((r) => ({ created_at: now, updated_at: now, ...DEFAULTS[table], ...r }));
  return [
    `-- ${table} (${rows.length})`,
    `INSERT INTO public.${table}`,
    `SELECT * FROM jsonb_populate_recordset(NULL::public.${table}, ${sqlLiteral(rows)}::jsonb)`,
    `ON CONFLICT ${conflict} DO NOTHING;`,
    '',
  ].join('\n');
}

const now = new Date().toISOString();
const noAuthor = <T extends object>(r: T) => ({ ...r, author_id: null });

const courses = seed.INITIAL_COURSES.map((c) => ({ ...c, id: toUuid(c.id) }));
const channels = seed.INITIAL_CHANNELS.map((c) => ({ ...c, id: toUuid(c.id), course_id: toUuid(c.course_id) }));
const news = seed.INITIAL_NEWS.map((n) => noAuthor({ ...n, id: toUuid(n.id) }));
const videos = seed.INITIAL_VIDEOS.map((v) => noAuthor({ ...v, id: toUuid(v.id) }));
const performers = seed.INITIAL_TOP_PERFORMERS.map((p) => noAuthor({ ...p, id: toUuid(p.id) }));


const lessons = seed.INITIAL_LICENSE_LESSONS.map((l) => {
  const type = l.content_type || l.lesson_type || 'video';
  const published = l.is_published ?? l.status !== 'draft';
  return noAuthor({
    ...l,
    content_type: type,
    lesson_type: type,
    is_published: published,
    status: published ? 'published' : 'draft',
  });
});

const resources = seed.INITIAL_SKILL_RESOURCES.map((r) => {
  const published = r.is_published ?? r.status !== 'draft';
  return noAuthor({ ...r, is_published: published, status: published ? 'published' : 'draft' });
});

const out = [
  '-- ====================================================================',
  '-- KBZLife LMS demo content seed (generated by scripts/generate-seed.ts)',
  '-- Run AFTER all migrations, in the Supabase SQL editor or with:',
  '--   psql "$DATABASE_URL" -f supabase/seed.sql',
  '-- ====================================================================',
  'BEGIN;',
  '',
  insert('courses', courses),
  insert('channels', channels),
  insert('company_news', news),
  insert('company_videos', videos),
  insert('top_performers', performers),
  insert('hod_motto', [seed.INITIAL_HOD_MOTTO]),
  insert('ld_team_members', seed.INITIAL_TEAM_MEMBERS),
  insert('license_chapters', seed.INITIAL_LICENSE_CHAPTERS.map(noAuthor)),
  insert('license_training_lessons', lessons),
  insert('license_quizzes', seed.INITIAL_LICENSE_QUIZZES),
  insert('skill_categories', seed.INITIAL_SKILL_CATEGORIES),
  insert('skill_development_resources', resources),
  insert('skill_quizzes', seed.INITIAL_SKILL_QUIZZES),
  insert('product_knowledge_items', seed.INITIAL_PRODUCTS.map(noAuthor)),
  insert('product_quizzes', seed.INITIAL_PRODUCT_QUIZZES),
  insert('company_bulletins', seed.INITIAL_COMPANY_BULLETINS.map((b) => noAuthor(b))),
  'COMMIT;',
  '',
].join('\n');

const target = path.resolve('supabase/seed.sql');
fs.writeFileSync(target, out);
console.log(`Wrote ${target} (${(out.length / 1024).toFixed(1)} KB)`);
